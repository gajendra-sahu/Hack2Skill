USE DATABASE REGINTEL360; USE SCHEMA RISK;
TRUNCATE TABLE RISK_ALERTS;
INSERT INTO RISK_ALERTS
WITH x AS (
 SELECT t.*, COUNT(*) OVER(PARTITION BY CUSTOMER_ID, TO_DATE(TRANSACTION_TS)) DAILY_CNT,
 COUNT_IF(AMOUNT BETWEEN 8500 AND 9999.99) OVER(PARTITION BY CUSTOMER_ID, TO_DATE(TRANSACTION_TS)) STRUCT_CNT
 FROM TRANSACTIONS t), s AS (
 SELECT *, (IFF(STRUCT_CNT>=3,45,0)+IFF(DAILY_CNT>=6,30,0)+IFF(AMOUNT>=25000,15,0)+IFF(MERCHANT_CATEGORY IN ('CRYPTO','GAMING','CASH_EQUIVALENT'),20,0)) SCORE FROM x)
SELECT 'ALERT-'||TRANSACTION_ID, TRANSACTION_ID, CUSTOMER_ID,
 CASE WHEN STRUCT_CNT>=3 THEN 'STRUCTURING' WHEN DAILY_CNT>=6 THEN 'RAPID_VELOCITY' WHEN MERCHANT_CATEGORY IN ('CRYPTO','GAMING','CASH_EQUIVALENT') THEN 'HIGH_RISK_MERCHANT' WHEN AMOUNT>=25000 THEN 'HIGH_VALUE' ELSE 'REVIEW' END,
 LEAST(SCORE,100), 'Synthetic rule evidence: daily_cnt='||DAILY_CNT||', structuring_count='||STRUCT_CNT||', amount='||AMOUNT||', merchant='||MERCHANT_CATEGORY, CURRENT_TIMESTAMP()
FROM s WHERE SCORE>=30;
