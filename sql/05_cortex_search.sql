USE DATABASE REGINTEL360; USE SCHEMA RISK;
CREATE OR REPLACE CORTEX SEARCH SERVICE REGULATORY_SEARCH
  ON CONTENT
  PRIMARY KEY (DOCUMENT_ID)
  ATTRIBUTES DOMAIN, AUTHORITY
  WAREHOUSE = REGINTEL360_WH
  TARGET_LAG = '1 hour'
  AS SELECT DOCUMENT_ID,TITLE,DOMAIN,AUTHORITY,EFFECTIVE_DATE,CONTENT FROM REGULATORY_DOCUMENTS;
